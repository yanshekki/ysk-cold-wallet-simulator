export function isLabLang(value: string | null | undefined): value is LabLang {
  return !!value && LAB_LANGUAGES.some((item) => item.id === value);
}

export function isRtl(language: LabLang): boolean {
  return language === 'ar';
}

export function detectLabLanguage(tag = ''): LabLang {
  if (/^zh/i.test(tag)) {
    return 'zh-HK';
  }
  if (/^pt/i.test(tag)) {
    return 'pt';
  }
  const code = tag.split('-')[0] ?? '';
  return isLabLang(code) ? code : 'en';
}

export function t(lang: LabLang, key: CopyKey): string {
  return COPY[lang][key] ?? COPY.en[key];
}
